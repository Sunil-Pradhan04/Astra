@router.post("/session/start")
async def start_kiosk_session(
    data: StartSessionRequest,
    device: EndpointDevice = Depends(get_current_device),
):
    """
    Starts a new 3-phase AI interrogation session for a patient.
    Returns Phase-1 Question 1 (explain your symptoms) immediately.
    """
    pid = data.patient_id.strip().upper()
    patient = await Patient.find_one(
        Patient.patient_id == pid,
        Patient.care_hub_id == device.care_hub_id,
    )
    if not patient:
        raise HTTPException(404, f"Patient {pid} not found in this facility")

    patient.status = "in_ai_session"
    await patient.save()

    lang_meta = get_lang_meta(data.language)
    lang_code = lang_meta["code"]
    lang_name = lang_meta["name"]
    speaker = lang_meta["speaker"]
    engine_choice = data.tts_engine or "local"

    # Generate Phase-1 Q1 in patient's language
    q1_data = await sarvam_ai.generate_primary_question(1, data.language)
    q1_en = q1_data["question_text_en"]
    q1_text = q1_data["question_text"]

    # Synthesize audio
    q1_audio, engine_used = await synthesize_speech(
        text=q1_text, lang_code=lang_code, speaker=speaker, engine=engine_choice
    )

    session_id = f"kiosk_session_{uuid.uuid4().hex[:12]}"
    memory = {
        "session_id": session_id,
        "patient_id": pid,
        "device_id": device.device_id,
        "care_hub_id": device.care_hub_id,
        "language": lang_code,
        "language_name": lang_name,
        "speaker": speaker,
        "tts_engine": engine_choice,
        "status": "in_progress",
        "phase": "phase_1",              # Current interrogation phase
        "started_at": datetime.utcnow().isoformat(),
        "rag_candidates": [],            # Will be populated after Phase 1
        "symptoms_summary": "",          # Extracted symptom list (English) for Pinecone
        "questions": [
            {
                "id": 1,
                "phase": "phase_1",
                "flag": "asked",
                "clinical_intent": "Open symptom disclosure",
                "question_text_en": q1_en,
                "question_text": q1_text,
                "patient_answer": None,
                "patient_answer_en": None,
                "timestamp": datetime.utcnow().isoformat(),
            }
        ],
        "ai_summary": None,
    }

    await session_memory.save_session(session_id, memory)

    device.is_online = True
    device.last_seen_at = datetime.utcnow()
    await device.save()

    return {
        "session_id": session_id,
        "patient_id": pid,
        "language": lang_name,
        "language_code": lang_code,
        "phase": "phase_1",
        "tts_engine": engine_used,
        "current_question": q1_text,
        "current_question_en": q1_en,
        "question_intent": "Open symptom disclosure",
        "audio_base64": q1_audio,
        "questions_status": _build_questions_status(memory["questions"]),
    }


@router.post("/session/reply-text")
async def reply_text(
    data: SessionTextReplyRequest,
    device: EndpointDevice = Depends(get_current_device),
):
    """Processes a typed (or pre-transcribed) patient answer."""
    return await _process_reply(
        session_id=data.session_id,
        patient_id=data.patient_id,
        answer_text=data.answer_text,
        tts_engine=data.tts_engine or "local",
        device=device,
    )


@router.post("/session/reply-audio")
async def reply_audio(
    session_id: str = Form(...),
    patient_id: str = Form(...),
    audio_file: UploadFile = File(...),
    tts_engine: str = Form("local"),
    device: EndpointDevice = Depends(get_current_device),
):
    """
    Receives voice audio, transcribes via Sarvam STT, then continues interrogation.
    """
    audio_bytes = await audio_file.read()

    memory = await session_memory.get_session(session_id)
    lang_code = memory.get("language") if memory else "unknown"

    transcript = await sarvam_ai.speech_to_text(
        audio_bytes=audio_bytes,
        filename=audio_file.filename or "recording.webm",
        content_type=audio_file.content_type or "audio/webm",
        lang_code=lang_code,
    )
    if not transcript:
        raise HTTPException(
            400,
            "Could not transcribe voice. Please speak closer to the microphone or type your answer."
        )

    return await _process_reply(
        session_id=session_id,
        patient_id=patient_id,
        answer_text=transcript,
        tts_engine=tts_engine or "local",
        device=device,
        transcribed_text=transcript,
    )


# ── Core reply processor ────────────────────────────────────────────────────

async def _process_reply(
    session_id: str,
    patient_id: str,
    answer_text: str,
    tts_engine: str,
    device: EndpointDevice,
    transcribed_text: Optional[str] = None,
) -> Dict[str, Any]:

    memory = await session_memory.get_session(session_id)
    if not memory:
        raise HTTPException(404, "Active interrogation session not found or expired.")

    lang_code = memory["language"]
    lang_name = memory["language_name"]
    speaker = memory.get("speaker", "priya")
    engine_choice = tts_engine or memory.get("tts_engine", "local")
    memory["tts_engine"] = engine_choice

    questions = memory["questions"]
    current_phase = memory.get("phase", "phase_1")

    # 1. Translate patient answer to English for clinical memory
    answer_clean = answer_text.strip()
    if lang_code != "en-IN":
        answer_en = await sarvam_ai.translate(answer_clean, source_lang=lang_code, target_lang="en-IN")
    else:
        answer_en = answer_clean

    # 2. Find the currently pending (asked, unanswered) question
    pending_q = next(
        (q for q in questions if q["flag"] == "asked" and q.get("patient_answer") is None),
        None
    )

    # 2a. LLM Answer Adequacy Validation ─────────────────────────────────────
    #   For phases 2 & 3 (where questions have specific clinical intents), check
    #   whether the patient actually answered or is requesting a repeat / saying
    #   they could not hear.  Phase 1 open narrative questions are always lenient.
    if pending_q and current_phase in ("phase_2", "phase_3"):
        q_en = pending_q.get("question_text_en", "")
        q_lang = pending_q.get("question_text") or q_en
        adequacy = await _validate_answer_adequacy(
            question_en=q_en,
            patient_answer_en=answer_en,
            question_in_patient_lang=q_lang,
            patient_lang_name=lang_name,
            lang_code=lang_code,
            speaker=speaker,
            engine_choice=engine_choice,
        )

        if not adequacy["is_valid"]:
            # Do NOT record the answer — re-ask the same question
            repeat_msg = adequacy["repeat_message"]
            repeat_audio = adequacy["repeat_audio"]
            await session_memory.save_session(session_id, memory)
            return _build_response(
                session_id, patient_id, is_complete=False,
                answer_clean=answer_clean, answer_en=answer_en,
                transcribed_text=transcribed_text,
                current_question=repeat_msg,
                current_question_en=q_en,
                question_intent=pending_q.get("clinical_intent", "Repeat question"),
                phase=current_phase,
                engine_used=engine_choice,
                audio_base64=repeat_audio,
                questions=questions,
                repeat_requested=True,
            )

    # 2b. Record valid answer for the currently pending question
    if pending_q:
        pending_q["patient_answer"] = answer_clean
        pending_q["patient_answer_en"] = answer_en

    # ─── PHASE 1: Open Symptom Disclosure ─────────────────────────────────
    if current_phase == "phase_1":
        q1_answered = any(
            q["id"] == 1 and q.get("patient_answer_en")
            for q in questions
        )
        q2_obj = next((q for q in questions if q.get("phase") == "phase_1" and q["id"] == 2), None)

        if q1_answered and q2_obj is None:
            # Q1 answered — ask Q2 ("did you miss anything?")
            q2_data = await sarvam_ai.generate_primary_question(2, lang_name.lower())
            q2_entry = {
                "id": 2,
                "phase": "phase_1",
                "flag": "asked",
                "clinical_intent": "Ensure full symptom disclosure",
                "question_text_en": q2_data["question_text_en"],
                "question_text": q2_data["question_text"],
                "patient_answer": None,
                "patient_answer_en": None,
                "timestamp": datetime.utcnow().isoformat(),
            }
            questions.append(q2_entry)

            q2_audio, engine_used = await synthesize_speech(
                text=q2_data["question_text"], lang_code=lang_code,
                speaker=speaker, engine=engine_choice
            )
            await session_memory.save_session(session_id, memory)

            return _build_response(
                session_id, patient_id, is_complete=False,
                answer_clean=answer_clean, answer_en=answer_en,
                transcribed_text=transcribed_text,
                current_question=q2_data["question_text"],
                current_question_en=q2_data["question_text_en"],
                question_intent="Ensure full symptom disclosure",
                phase="phase_1",
                engine_used=engine_used,
                audio_base64=q2_audio,
                questions=questions,
            )

        elif q2_obj and q2_obj.get("patient_answer_en"):
            # Both Q1 and Q2 answered → transition to PHASE 2 (RAG)
            phase1_answers_en = [
                q.get("patient_answer_en", "")
                for q in questions
                if q.get("phase") == "phase_1" and q.get("patient_answer_en")
            ]
            symptoms_summary = await rag_triage.extract_symptom_summary(phase1_answers_en)
            memory["symptoms_summary"] = symptoms_summary

            # Retrieve candidate diseases from Pinecone
            candidates = await rag_triage.retrieve_candidate_diseases(symptoms_summary, top_k=5)
            memory["rag_candidates"] = candidates

            # Generate Phase-2 follow-up questions via Sarvam AI
            already_intents = ["Open symptom disclosure", "Ensure full symptom disclosure"]
            rag_questions = await rag_triage.generate_rag_followup_questions(
                symptoms_summary=symptoms_summary,
                candidate_diseases=candidates,
                already_asked_intents=already_intents,
                lang_name=lang_name,
                lang_code=lang_code,
            )

            # Add Phase 2 questions to memory
            q_id = len(questions) + 1
            for idx, rq in enumerate(rag_questions):
                questions.append({
                    "id": q_id + idx,
                    "phase": "phase_2",
                    "flag": "not_asked",
                    "clinical_intent": rq.get("clinical_intent", "RAG differential follow-up"),
                    "target_differential": rq.get("target_differential", ""),
                    "question_text_en": rq["question_text_en"],
                    "question_text": rq.get("question_text", rq["question_text_en"]),
                    "patient_answer": None,
                    "patient_answer_en": None,
                    "timestamp": None,
                })

            memory["phase"] = "phase_2"
            return await _ask_next_in_phase(
                memory, questions, session_id, patient_id, "phase_2",
                lang_code, speaker, engine_choice,
                answer_clean, answer_en, transcribed_text
            )

    # ─── PHASE 2: RAG Follow-up Questions ─────────────────────────────────
    elif current_phase == "phase_2":
        remaining = [
            q for q in questions
            if q.get("phase") == "phase_2" and q["flag"] == "not_asked"
        ]

        if remaining:
            # Still have RAG questions to ask
            return await _ask_next_in_phase(
                memory, questions, session_id, patient_id, "phase_2",
                lang_code, speaker, engine_choice,
                answer_clean, answer_en, transcribed_text
            )
        else:
            # Phase 2 complete → generate Phase 3 detail questions
            candidates = memory.get("rag_candidates", [])
            symptoms_summary = memory.get("symptoms_summary", "")

            detail_questions = await rag_triage.generate_detail_questions(
                symptoms_summary=symptoms_summary,
                candidate_diseases=candidates,
                lang_name=lang_name,
                lang_code=lang_code,
            )

            q_id = len(questions) + 1
            for idx, dq in enumerate(detail_questions):
                questions.append({
                    "id": q_id + idx,
                    "phase": "phase_3",
                    "flag": "not_asked",
                    "clinical_intent": dq.get("clinical_intent", "Clinical detail"),
                    "detail_type": dq.get("detail_type", ""),
                    "question_text_en": dq["question_text_en"],
                    "question_text": dq.get("question_text", dq["question_text_en"]),
                    "patient_answer": None,
                    "patient_answer_en": None,
                    "timestamp": None,
                })

            memory["phase"] = "phase_3"
            return await _ask_next_in_phase(
                memory, questions, session_id, patient_id, "phase_3",
                lang_code, speaker, engine_choice,
                answer_clean, answer_en, transcribed_text
            )

    # ─── PHASE 3: Clinical Detail Questions ────────────────────────────────
    elif current_phase == "phase_3":
        remaining = [
            q for q in questions
            if q.get("phase") == "phase_3" and q["flag"] == "not_asked"
        ]

        if remaining:
            return await _ask_next_in_phase(
                memory, questions, session_id, patient_id, "phase_3",
                lang_code, speaker, engine_choice,
                answer_clean, answer_en, transcribed_text
            )
        else:
            # ── Phase 3 complete → Inquire if patient has medical prescription/report to show ──
            memory["phase"] = "phase_prescription_prompt"

            rx_q_text = _get_localized_rx_prompt(lang_code)
            rx_q_en = "Do you have any doctor's prescription, medical note, or test report to show to the camera?"

            q_id = len(questions) + 1
            rx_entry = {
                "id": q_id,
                "phase": "phase_prescription_prompt",
                "flag": "asked",
                "clinical_intent": "Inquire about prescription/medical report",
                "question_text_en": rx_q_en,
                "question_text": rx_q_text,
                "patient_answer": None,
                "patient_answer_en": None,
                "timestamp": datetime.utcnow().isoformat(),
            }
            questions.append(rx_entry)

            rx_audio, engine_used = await synthesize_speech(
                text=rx_q_text, lang_code=lang_code, speaker=speaker, engine=engine_choice
            )
            await session_memory.save_session(session_id, memory)

            return {
                "session_id": session_id,
                "patient_id": patient_id,
                "is_complete": False,
                "phase": "phase_prescription_prompt",
                "is_prescription_prompt": True,
                "patient_answer_recorded": answer_clean,
                "patient_answer_en": answer_en,
                "transcribed_text": transcribed_text,
                "current_question": rx_q_text,
                "current_question_en": rx_q_en,
                "question_intent": "Inquire about prescription/medical report",
                "tts_engine": engine_used,
                "audio_base64": rx_audio,
                "questions_status": _build_questions_status(questions),
            }

    # ─── PHASE: Prescription Inquiry Answer ────────────────────────────────
    elif current_phase == "phase_prescription_prompt":
        intent = await _classify_prescription_inquiry_intent(answer_en, answer_clean)

        if intent == "repeat":
            rx_q_text = _get_localized_rx_prompt(lang_code)

            rx_audio, engine_used = await synthesize_speech(
                text=rx_q_text, lang_code=lang_code, speaker=speaker, engine=engine_choice
            )
            await session_memory.save_session(session_id, memory)

            return {
                "session_id": session_id,
                "patient_id": patient_id,
                "is_complete": False,
                "phase": "phase_prescription_prompt",
                "is_prescription_prompt": True,
                "patient_answer_recorded": answer_clean,
                "patient_answer_en": answer_en,
                "transcribed_text": transcribed_text,
                "current_question": rx_q_text,
                "current_question_en": "Do you have any doctor's prescription, medical note, or test report to show to the camera?",
                "question_intent": "Inquire about prescription/medical report",
                "tts_engine": engine_used,
                "audio_base64": rx_audio,
                "questions_status": _build_questions_status(questions),
                "repeat_requested": True,
            }

        elif intent == "yes":
            # Patient has a prescription -> open camera / upload page immediately!
            memory["phase"] = "phase_prescription_camera"

            cam_guidance = _get_localized_cam_guidance(lang_code)
            cam_guidance_en = "Please hold your prescription or report steady in front of the camera to take a photo, or upload an image."

            cam_audio, engine_used = await synthesize_speech(
                text=cam_guidance, lang_code=lang_code, speaker=speaker, engine=engine_choice
            )
            await session_memory.save_session(session_id, memory)

            return {
                "session_id": session_id,
                "patient_id": patient_id,
                "is_complete": False,
                "phase": "phase_prescription_camera",
                "open_camera": True,
                "patient_answer_recorded": answer_clean,
                "patient_answer_en": answer_en,
                "transcribed_text": transcribed_text,
                "current_question": cam_guidance,
                "current_question_en": cam_guidance_en,
                "question_intent": "Camera prescription capture",
                "tts_engine": engine_used,
                "audio_base64": cam_audio,
                "questions_status": _build_questions_status(questions),
            }
        else:
            # Patient has NO prescription -> proceed to final summary directly
            return await _finalize_session_summary(
                session_id=session_id,
                patient_id=patient_id,
                memory=memory,
                device=device,
                answer_clean=answer_clean,
                answer_en=answer_en,
                transcribed_text=transcribed_text,
                lang_code=lang_code,
                lang_name=lang_name,
                speaker=speaker,
                engine_choice=engine_choice,
            )

    # Fallback safety net
    await session_memory.save_session(session_id, memory)
    return _build_response(
        session_id, patient_id, is_complete=False,
        answer_clean=answer_clean, answer_en=answer_en,
        transcribed_text=transcribed_text,
        current_question="Please continue describing your symptoms.",
        current_question_en="Please continue describing your symptoms.",
        question_intent="Follow-up",
        phase=current_phase,
        engine_used=engine_choice,
        audio_base64=None,
        questions=questions,
    )


# ── Prescription Inquiry Intent Classifier ─────────────────────────────────

async def _classify_prescription_inquiry_intent(answer_en: str, answer_clean: str) -> str:
    """
    Classifies patient response to prescription prompt.
    Returns: 'yes' (wants to show document/prescription), 'no' (no document), or 'repeat' (could not hear/understand).
    """
    clean_lower = (answer_clean or "").strip().lower()
    en_lower = (answer_en or "").strip().lower()
    combined = f"{en_lower} {clean_lower}"

    # 1. Quick check for repeat request
    repeat_words = ["repeat", "again", "say again", "ask again", "hear", "pardon", "sorry", "kya bola", "sunai", "phir se", "samajh nahi"]
    if any(rw in combined for rw in repeat_words):
        return "repeat"

    # 2. Strong negative indicators
    negative_patterns = [
        "no", "not", "nahi", "nahin", "don't", "none", "nhi", "kuch nahi",
        "kichhi nahi", "nothing", "skip", "ନାହିଁ", "ନା", "नहीं", "कोई पर्चा नहीं",
        "இல்லை", "illai", "లేదు", "ledu", "না", "নেই", "na",
        "ഇല്ല", "illa", "नाही", "nahi", "નથી", "nathi", "ಇಲ್ಲ", "illa", "ਨਹੀਂ", "nahin"
    ]
    # 3. Strong positive indicators
    positive_patterns = [
        "yes", "yeah", "yup", "sure", "have", "present", "prescription", "report",
        "parcha", "pacha", "dikha", "show", "upload", "scan", "camera", "photo",
        "achhi", "achi", "haan", "ha", "hai", "हाँ", "हां", "ଅଛି", "ହଁ", "ଦେଖାଇବି", "दिखाना",
        "ஆம்", "உள்ளது", "aam", "ullathu", "అవును", "ఉంది", "avunu", "undi",
        "হ্যাঁ", "আছে", "hyan", "achhe", "അതെ", "ഉണ്ട്", "athe", "undu",
        "होय", "आहे", "hoy", "aahe", "હા", "છે", "haa", "chhe",
        "ಹೌದು", "ಇದೆ", "haudu", "ide", "ਹਾਂ", "ਹੈ", "haan", "hai"
    ]

    has_neg = any(nw in combined for nw in negative_patterns)
    has_pos = any(pw in combined for pw in positive_patterns)

    if has_pos and not has_neg:
        return "yes"
    if has_neg and not has_pos:
        return "no"

    # 4. If ambiguous, use Sarvam LLM
    try:
        prompt = (
            f"A patient at a medical kiosk was asked: 'Do you have any doctor prescription or medical test report to show to the camera?'\n"
            f"Patient answered: \"{answer_clean}\" (English translation: \"{answer_en}\")\n\n"
            f"Does the patient indicate they HAVE a prescription/report and want to show it, or do they NOT have one, or do they ask to REPEAT?\n"
            f"Respond with ONLY ONE WORD: YES, NO, or REPEAT."
        )
        res = await sarvam_ai.generate_completion(
            system_prompt="You are a clinical triage intent classifier. Output ONLY: YES, NO, or REPEAT.",
            user_prompt=prompt,
            temperature=0.0,
            max_tokens=10,
        )
        norm = res.strip().upper()
        if "YES" in norm:
            return "yes"
        elif "REPEAT" in norm:
            return "repeat"
        else:
            return "no"
    except Exception as e:
        print(f"[Kiosk] Prescription intent classification exception: {e}")
        return "yes" if has_pos else "no"


# ── Answer Adequacy Validator ──────────────────────────────────────────────

async def _validate_answer_adequacy(
    question_en: str,
    patient_answer_en: str,
    question_in_patient_lang: str,
    patient_lang_name: str,
    lang_code: str,
    speaker: str,
    engine_choice: str,
) -> Dict[str, Any]:
    """
    Uses Sarvam LLM to check if the patient's reply is a genuine clinical answer.
    Returns:
        {
          "is_valid": bool,
          "repeat_message": str | None,  # polite re-ask in patient's language
          "repeat_audio": str | None,    # base64 audio of repeat_message
        }
    """
    try:
        prompt = build_answer_adequacy_prompt(
            question_en=question_en,
            patient_answer_en=patient_answer_en,
            question_in_patient_lang=question_in_patient_lang,
            patient_lang_name=patient_lang_name,
        )
        raw = await sarvam_ai.generate_completion(
            system_prompt=ANSWER_ADEQUACY_SYSTEM,
            user_prompt=prompt,
            temperature=0.05,
            max_tokens=300,
        )

        # Strip markdown code fences if present
        clean = raw.strip()
        if "```" in clean:
            clean = re.sub(r"^```(?:json)?\s*", "", clean, flags=re.MULTILINE)
            clean = re.sub(r"\s*```$", "", clean, flags=re.MULTILINE)

        parsed = json.loads(clean)
        is_valid = bool(parsed.get("is_valid_answer", True))

        if not is_valid:
            repeat_msg = parsed.get("repeat_message") or question_in_patient_lang
            repeat_audio, _ = await synthesize_speech(
                text=repeat_msg, lang_code=lang_code, speaker=speaker, engine=engine_choice
            )
            return {"is_valid": False, "repeat_message": repeat_msg, "repeat_audio": repeat_audio}

    except Exception as e:
        print(f"[Kiosk] Answer adequacy validation error (defaulting to valid): {e}")

    # If LLM call failed or returned valid — advance normally
    return {"is_valid": True, "repeat_message": None, "repeat_audio": None}


# ── Internal helper: mark next question as asked & return response ─────────

async def _ask_next_in_phase(
    memory: dict,
    questions: List[dict],
    session_id: str,
    patient_id: str,
    phase: str,
    lang_code: str,
    speaker: str,
    engine_choice: str,
    answer_clean: str,
    answer_en: str,
    transcribed_text: Optional[str],
) -> Dict[str, Any]:
    """
    Finds the first not_asked question in `phase`, marks it as asked,
    synthesizes audio, saves memory, and returns response.
    """
    next_q = next(
        (q for q in questions if q.get("phase") == phase and q["flag"] == "not_asked"),
        None
    )

    if not next_q:
        # Should not happen — caller handles this
        raise HTTPException(500, "No pending questions found for current phase.")

    next_q["flag"] = "asked"
    next_q["timestamp"] = datetime.utcnow().isoformat()

    q_text = next_q.get("question_text") or next_q["question_text_en"]
    q_text_en = next_q["question_text_en"]
    q_intent = next_q.get("clinical_intent", "Clinical follow-up")

    audio, engine_used = await synthesize_speech(
        text=q_text, lang_code=lang_code, speaker=speaker, engine=engine_choice
    )
    await session_memory.save_session(session_id, memory)

    return _build_response(
        session_id, patient_id, is_complete=False,
        answer_clean=answer_clean, answer_en=answer_en,
        transcribed_text=transcribed_text,
        current_question=q_text,
        current_question_en=q_text_en,
        question_intent=q_intent,
        phase=phase,
        engine_used=engine_used,
        audio_base64=audio,
        questions=questions,
    )


def _build_response(
    session_id, patient_id, is_complete, answer_clean, answer_en,
    transcribed_text, current_question, current_question_en,
    question_intent, phase, engine_used, audio_base64, questions,
    repeat_requested: bool = False,
) -> Dict[str, Any]:
    return {
        "session_id": session_id,
        "patient_id": patient_id,
        "is_complete": is_complete,
        "phase": phase,
        "patient_answer_recorded": answer_clean,
        "patient_answer_en": answer_en,
        "transcribed_text": transcribed_text,
        "current_question": current_question,
        "current_question_en": current_question_en,
        "question_intent": question_intent,
        "tts_engine": engine_used,
        "audio_base64": audio_base64,
        "repeat_requested": repeat_requested,  # True when AI re-asks same question
        "questions_status": _build_questions_status(questions),
    }



# ── Session Finalizer Helper ───────────────────────────────────────────────

async def _finalize_session_summary(
    session_id: str,
    patient_id: str,
    memory: dict,
    device: EndpointDevice,
    answer_clean: str,
    answer_en: str,
    transcribed_text: Optional[str],
    lang_code: str,
    lang_name: str,
    speaker: str,
    engine_choice: str,
    prescription_data: Optional[dict] = None,
) -> Dict[str, Any]:
    """Generates the final comprehensive clinical summary and concludes interrogation."""
    await session_memory.save_session(session_id, memory)
    ai_summary = await rag_triage.generate_final_summary(memory, prescription_data=prescription_data)

    concluding_text = (
        ai_summary.get("concluding_message")
        or ai_summary.get("concluding_message_en")
        or "Thank you. Your symptoms have been recorded. A health worker will review your case shortly."
    )

    concluding_audio, engine_used = await synthesize_speech(
        text=concluding_text,
        lang_code=lang_code, speaker=speaker, engine=engine_choice
    )

    # Update patient record in MongoDB
    patient = await Patient.find_one(
        Patient.patient_id == patient_id,
        Patient.care_hub_id == device.care_hub_id,
    )
    if patient:
        patient.status = "pending_verification"
        patient.chief_complaints = ai_summary.get("chief_complaints", "Completed via AI kiosk")

        structured_ai_summary = {
            "structured_summary": ai_summary,
            "rag_candidates": memory.get("rag_candidates", []),
            "symptoms_extracted": memory.get("symptoms_summary", ""),
            "interrogation_completed_at": datetime.utcnow().isoformat(),
            "device_id": device.device_id,
            "language": lang_name,
            "tts_engine_used": engine_used,
            "total_questions_asked": len([q for q in memory.get("questions", []) if q.get("flag") == "asked"]),
            "phases_completed": ["phase_1", "phase_2", "phase_3", "prescription_check"],
        }
        if prescription_data:
            structured_ai_summary["prescription_data"] = prescription_data

        patient.ai_summary = structured_ai_summary
        await patient.save()

    memory["status"] = "completed"
    memory["phase"] = "complete"
    memory["ai_summary"] = ai_summary
    if prescription_data:
        memory["prescription_data"] = prescription_data
    await session_memory.save_session(session_id, memory)

    return {
        "session_id": session_id,
        "patient_id": patient_id,
        "is_complete": True,
        "phase": "complete",
        "patient_answer_recorded": answer_clean,
        "patient_answer_en": answer_en,
        "transcribed_text": transcribed_text,
        "concluding_message": concluding_text,
        "tts_engine": engine_used,
        "audio_base64": concluding_audio,
        "ai_summary": ai_summary,
        "prescription": prescription_data,
        "next_stage": "pending_verification",
        "questions_status": _build_questions_status(memory.get("questions", [])),
    }


