"""
Kiosk AI Interrogation Router — 3-Phase RAG Pipeline
=====================================================

PHASE 1 — Open Symptom Disclosure  (questions 1 & 2)
    Q1: "Please explain your symptoms clearly and deeply."
    Q2: "Did you miss anything? Please elaborate."
    After Q2 answer → extract symptom list → query Pinecone → generate Phase 2 questions

PHASE 2 — RAG Differential Follow-up  (3 Pinecone-informed questions)
    Questions generated by Sarvam AI based on retrieved candidate diseases.
    Targets discriminating symptoms NOT yet mentioned by the patient.

PHASE 3 — Clinical Detail Deep-dive  (5 targeted detail questions)
    Duration / Location / Severity / Pattern / Prior meds & history
    After completion → generate comprehensive final clinical summary

All question texts stored in English (canonical clinical memory).
TTS audio + display always in patient's preferred language.
"""

