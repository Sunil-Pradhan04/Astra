# ── Speech Synthesis Dispatcher (Local Kokoro vs Sarvam Cloud) ────────────────

async def synthesize_speech(
    text: str,
    lang_code: str,
    speaker: str = "priya",
    engine: str = "local",
) -> tuple[Optional[str], str]:
    """
    Synthesizes speech using the requested engine:
    - 'local': Uses hexgrad/Kokoro-82M on-device model (Free, Fast, Default).
    - 'sarvam': Uses Sarvam Indic cloud API (bulbul:v3).
    Returns: (audio_base64, engine_used)
    """
    engine_norm = (engine or "local").strip().lower()

    if engine_norm == "local":
        try:
            audio = await local_tts.text_to_speech(text, lang_code)
            if audio:
                return audio, "local"
        except Exception as e:
            print(f"[Kiosk] Local Kokoro TTS failed, falling back to Sarvam: {e}")
        audio = await sarvam_ai.text_to_speech(text, lang_code, speaker)
        return audio, "sarvam"
    else:
        try:
            audio = await sarvam_ai.text_to_speech(text, lang_code, speaker)
            if audio:
                return audio, "sarvam"
        except Exception as e:
            print(f"[Kiosk] Sarvam TTS failed, falling back to Local Kokoro: {e}")
        audio = await local_tts.text_to_speech(text, lang_code)
        return audio, "local"


